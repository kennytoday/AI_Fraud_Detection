import os
import joblib
import numpy as np


class FraudDetector:
    """
    This class is responsible for:
    1. Loading the saved machine learning model
    2. Making predictions
    3. Explaining the risk factors in plain English
    4. Turning the confidence score into LOW / MEDIUM / HIGH
    """

    def __init__(self, model_path="fraud_model.pkl"):
        # Start with no model loaded
        self.model = None

        # If the model file exists, load it
        if os.path.exists(model_path):
            self.model = joblib.load(model_path)

    def is_model_loaded(self):
        """Simple check: did we successfully load the model?"""
        return self.model is not None

    def predict(self, values):
        """
        Make a prediction for one transaction.

        values must be a list of 6 numbers in this exact order:
        [
            Amount,                 # e.g. 2500.50
            Hour,                   # 0 to 23
            PreviousTransactions,   # how many times this person has transacted before
            International,          # 1 = yes, 0 = no
            NewDevice,              # 1 = yes, 0 = no
            HighRiskCountry         # 1 = yes, 0 = no
        ]

        Returns:
            prediction  (0 = legitimate, 1 = fraud)
            confidence  (a number between 0 and 1)
        """
        if self.model is None:
            raise Exception(
                "Model not found.\n\nRun train_model.py first."
            )

        # The model expects a 2-D array, so we reshape the single row
        X = np.array(values).reshape(1, -1)

        # Get the prediction (0 or 1)
        prediction = int(self.model.predict(X)[0])

        # Get the probabilities for both classes
        # Example: [0.12, 0.88] means 12% legitimate, 88% fraud
        probability = self.model.predict_proba(X)[0]

        # Confidence = the higher of the two probabilities
        confidence = float(max(probability))

        return prediction, confidence

    def risk_factors(self, values):
        """
        Returns a list of simple, human-readable reasons
        why this transaction might look risky.

        Note: These rules are written by hand.
        They are NOT generated by the machine learning model itself.
        They just help the user understand the result.
        """
        amount           = values[0]
        hour             = values[1]
        previous         = values[2]
        international    = values[3]
        new_device       = values[4]
        high_risk_country = values[5]

        reasons = []

        if amount > 5000:
            reasons.append("Large transaction amount")

        if hour <= 5:
            reasons.append("Transaction occurred late at night")

        if previous == 0:
            reasons.append("No previous transaction history")

        if international:
            reasons.append("International transaction")

        if new_device:
            reasons.append("New device used")

        if high_risk_country:
            reasons.append("High-risk country")

        # If nothing matched, say so
        if len(reasons) == 0:
            reasons.append("No obvious risk factors")

        return reasons

    def risk_level(self, confidence):
        """
        Converts the model's confidence (0.0 to 1.0)
        into a simple label: LOW, MEDIUM, or HIGH.
        """
        percent = confidence * 100

        if percent < 50:
            return "LOW"
        elif percent < 80:
            return "MEDIUM"
        else:
            return "HIGH"
